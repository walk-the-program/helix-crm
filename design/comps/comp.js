  function sprite() {
    var parts = ['<svg xmlns="http://www.w3.org/2000/svg" style="position:absolute;width:0;height:0;overflow:hidden" aria-hidden="true">'];
    for (var k in ICONS) {
      var fill = k === "grip" ? ' fill="currentColor" stroke="none"' : "";
      parts.push('<symbol id="i-' + k + '" viewBox="0 0 24 24"' + fill + ">" + ICONS[k] + "</symbol>");
    }
    parts.push("</svg>");
    var host = document.createElement("div");
    host.innerHTML = parts.join("");
    document.body.insertBefore(host.firstChild, document.body.firstChild);
  }

  function apply(theme, density) {
    var el = document.documentElement;
    if (theme) el.setAttribute("data-theme", theme);
    if (density) el.setAttribute("data-density", density);
    var t = el.getAttribute("data-theme") === "dark" ? "dark" : "light";
    var d = el.getAttribute("data-density") === "compact" ? "compact" : "comfortable";
    var tb = document.getElementById("comp-theme");
    var db = document.getElementById("comp-density");
    if (tb) tb.textContent = t === "dark" ? "Light theme" : "Dark theme";
    if (db) db.textContent = d === "compact" ? "Comfortable" : "Compact";
  }

  function chrome() {
    var box = document.createElement("div");
    box.className = "comp-switch";
    box.setAttribute("data-print-hide", "");
    box.innerHTML =
      '<button id="comp-theme" type="button">Dark theme</button>' +
      '<button id="comp-density" type="button">Compact</button>';
    document.body.appendChild(box);

    box.querySelector("#comp-theme").addEventListener("click", function () {
      apply(document.documentElement.getAttribute("data-theme") === "dark" ? "light" : "dark", null);
    });
    box.querySelector("#comp-density").addEventListener("click", function () {
      apply(null, document.documentElement.getAttribute("data-density") === "compact" ? "comfortable" : "compact");
    });
  }

  function boot() {
    sprite();
    var q = new URLSearchParams(location.search);
    if (q.get("chrome") !== "off") chrome();
    apply(q.get("theme") === "dark" ? "dark" : "light",
          q.get("density") === "compact" ? "compact" : "comfortable");
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", boot);
  } else {
    boot();
  }
